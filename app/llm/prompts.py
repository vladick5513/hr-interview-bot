def _criterion_line(criterion: VacancyCriterion) -> str:
    must = "must-have, " if criterion.is_must_have else ""
    return (
        f"- id={criterion.id} [{must}вес {criterion.weight}] "
        f"{criterion.title}: {criterion.description}"
    )


def profile_user(
    vacancy_text: str,
    pool: list[str],
    mode: QuestionMode,
    previous: VacancyProfile | None,
    remarks: str | None,
) -> str:
    text = f"<vacancy>\n{vacancy_text[:MAX_VACANCY_CHARS]}\n</vacancy>"
    if pool:
        numbered = "\n".join(f"{n}. {q}" for n, q in enumerate(pool, start=1))
        text += f"\n\n<company_questions>\n{numbered}\n</company_questions>"
    text += f"\n\nЗадание по вопросам: {_MODE_TASKS[mode]}"
    if previous is not None:
        text += (
            f"\n\nПредыдущий вариант профиля:\n{previous.model_dump_json(indent=2)}\n\n"
            f"Переделай профиль с учётом замечаний рекрутера:\n{remarks}"
        )
    return text


def analyze_user(vacancy: Vacancy, resume_text: str, questions_count: int) -> str:
    covered = {q.criterion_id for q in vacancy.questions}
    criteria = "\n".join(
        _criterion_line(c)
        + (" — обязательный вопрос есть" if c.id in covered else " — обязательного вопроса нет")
        for c in vacancy.criteria
    )
    mandatory = "\n".join(f"- {q.text}" for q in vacancy.questions)
    return (
        f"Вакансия: {vacancy.title}\n{vacancy.description[:MAX_VACANCY_CHARS]}\n\n"
        f"Критерии:\n{criteria}\n\n"
        f"Обязательные вопросы:\n{mandatory}\n\n"
        f"Нужно персональных вопросов: {questions_count}\n\n"
        f"<resume>\n{resume_text[:MAX_RESUME_CHARS]}\n</resume>"
    )


def evaluate_user(
    vacancy_title: str,
    criterion: VacancyCriterion,
    resume_text: str,
    question: str,
    answer: str,
    follow_up: str | None,
    follow_up_answer: str | None,
) -> str:
    text = (
        f"Вакансия: {vacancy_title}\n"
        f"Критерий: {criterion.title} — {criterion.description}\n\n"
        f"Резюме кандидата (для поиска расхождений):\n"
        f"<resume>\n{resume_text[:MAX_RESUME_CHARS]}\n</resume>\n\n"
        f"Вопрос: {question}\n<answer>\n{answer}\n</answer>"
    )
    if follow_up is not None:
        text += (
            f"\n\nУточняющий вопрос (уже задан): {follow_up}\n"
            f"<follow_up_answer>\n{follow_up_answer}\n</follow_up_answer>"
        )
    return text
